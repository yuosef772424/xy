#!/usr/bin/env python3
"""Generate PROJECT_MAP.md: a compact map of the codebase for AI agents.

The map lists each module (a directory containing MODULE.md) with its one-line
purpose, and every source file with its line count, so an agent can find the
right place without reading the whole project.

Usage:
  python scripts/gen_map.py            # write PROJECT_MAP.md
  python scripts/gen_map.py --check    # exit 1 if PROJECT_MAP.md is stale (for CI)
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "PROJECT_MAP.md")
SKIP_DIRS = {".git", "node_modules", "dist", "build", "__pycache__", ".venv", "venv", "coverage"}
SOURCE_EXTS = {".py", ".js", ".ts", ".tsx", ".jsx", ".go", ".java", ".kt", ".rs", ".rb", ".php", ".cs", ".swift", ".sql"}


def read_purpose(module_md):
    """Return the 'purpose:' line from a MODULE.md file, or a warning marker."""
    with open(module_md, encoding="utf-8") as f:
        for line in f:
            if line.lower().startswith("purpose:"):
                return line.split(":", 1)[1].strip()
    return "⚠️ MODULE.md has no 'purpose:' line"


def count_lines(path):
    with open(path, encoding="utf-8", errors="ignore") as f:
        return sum(1 for _ in f)


def build_map():
    lines = [
        "# PROJECT_MAP",
        "",
        "> Auto-generated by `scripts/gen_map.py`. Do not edit by hand.",
        "> Read this first, then the relevant `MODULE.md`, then only the files you need.",
        "",
    ]
    missing = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        sources = sorted(f for f in filenames if os.path.splitext(f)[1] in SOURCE_EXTS)
        rel = os.path.relpath(dirpath, ROOT)
        if "MODULE.md" in filenames:
            purpose = read_purpose(os.path.join(dirpath, "MODULE.md"))
            lines.append(f"## `{rel}/` — {purpose}")
        elif sources:
            if rel != "scripts":
                missing.append(rel)
            lines.append(f"## `{rel}/`")
        else:
            continue
        for name in sources:
            n = count_lines(os.path.join(dirpath, name))
            lines.append(f"- `{name}` ({n} lines)")
        lines.append("")
    if missing:
        lines.append("## ⚠️ Directories with source files but no MODULE.md")
        lines.extend(f"- `{m}/`" for m in missing)
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if PROJECT_MAP.md is out of date")
    args = parser.parse_args()
    content = build_map()
    if args.check:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else ""
        if current != content:
            print("PROJECT_MAP.md is stale. Run: python scripts/gen_map.py", file=sys.stderr)
            return 1
        print("PROJECT_MAP.md is up to date.")
        return 0
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Wrote {os.path.relpath(OUTPUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
